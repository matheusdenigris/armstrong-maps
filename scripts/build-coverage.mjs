/**
 * Writes `src/data/coverage.ts`: the area of every regional image mosaic that NASA's Mars Trek
 * publishes, read from its own catalogue. The docs count these areas; the globe does not mark them.
 *
 *   node scripts/build-coverage.mjs
 *
 * A regional image mosaic is a catalogue product in the category Imagery, Mosaic, from an orbital
 * camera, whose area is a part of the planet. Elevation models, slope maps, hillshades and the
 * mosaics of the whole planet are left out. Nothing is drawn by hand: run this again to follow
 * the catalogue.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const CATALOGUE =
  'https://trek.nasa.gov/mars/TrekServices/ws/index/eq/searchItems' +
  '?proj=urn:ogc:def:crs:EPSG::104905&start=0&rows=1000&facetKeys=itemType&facetValues=product';

/** Wider than this is a map of the planet or of a hemisphere, not a region. */
const WIDEST_DEG = 90;
/** Narrower than this is a catalogue entry without a real area. */
const NARROWEST_DEG = 0.001;

const round = (value) => Math.round(value * 1e4) / 1e4;

const response = await fetch(CATALOGUE);
if (!response.ok) throw new Error(`The Mars Trek catalogue answered ${response.status}`);
const { response: found } = await response.json();
if (found.numFound > found.docs.length) {
  throw new Error(`The catalogue has ${found.numFound} products and sent ${found.docs.length}`);
}

const areas = [];
for (const product of found.docs) {
  if (product.productCat1 !== 'Imagery' || product.productCat2 !== 'Mosaic') continue;
  if (!product.instrument || !product.bbox) continue;
  const [west, south, east, north] = product.bbox.split(',').map(Number);
  if (![west, south, east, north].every(Number.isFinite)) continue;
  const width = east - west;
  const height = north - south;
  if (width < NARROWEST_DEG || height < NARROWEST_DEG || width > WIDEST_DEG) continue;
  if (south < -90 || north > 90) continue;
  areas.push({
    id: product.productLabel,
    title: product.title,
    instrument: product.instrument,
    // The catalogue counts some longitudes 0 to 360; the app stores -180 to 180.
    bounds: {
      west: round(west > 180 ? west - 360 : west),
      south: round(south),
      east: round(east > 180 ? east - 360 : east),
      north: round(north),
    },
  });
}
areas.sort((one, other) => one.id.localeCompare(other.id, 'en'));
if (areas.length === 0) throw new Error('The catalogue lists no regional mosaic');

const now = new Date();
const pad = (value) => String(value).padStart(2, '0');
const today = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
/** A string as the code of the app writes one: in single quotes. */
const quote = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lines = areas.map(
  ({ id, title, instrument, bounds }) =>
    `  { id: ${quote(id)}, title: ${quote(title)}, instrument: ${quote(instrument)}, ` +
    `bounds: { west: ${bounds.west}, south: ${bounds.south}, east: ${bounds.east}, north: ${bounds.north} } },`,
);

const file = `/**
 * Where NASA's Mars Trek (trek.nasa.gov, NASA/JPL) publishes regional image mosaics.
 *
 * Generated by \`scripts/build-coverage.mjs\` from the Mars Trek catalogue on ${today}. Do not
 * edit by hand: run the script again.
 */
import type { Bounds } from '@/mission/tiles';

export type CoverageArea = {
  /** Product id on Mars Trek. */
  id: string;
  title: string;
  /** The camera that took the images. */
  instrument: string;
  bounds: Bounds;
};

/** The day the catalogue was read. */
export const COVERAGE_READ_ON = '${today}';

export const COVERAGE_CREDIT = 'Mosaic areas from the NASA/JPL Mars Trek catalogue';

// prettier-ignore
export const COVERAGE: readonly CoverageArea[] = [
${lines.join('\n')}
];
`;

const target = fileURLToPath(new URL('../src/data/coverage.ts', import.meta.url));
writeFileSync(target, file);
const byInstrument = {};
for (const area of areas) byInstrument[area.instrument] = (byInstrument[area.instrument] ?? 0) + 1;
console.log(`Wrote ${areas.length} areas to src/data/coverage.ts`, byInstrument);
